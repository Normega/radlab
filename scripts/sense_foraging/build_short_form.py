"""The Sense Foraging Scale short form (20 items), chosen from Study 1 (Norm, 2026-10-11).

Four factors, five items each, every factor mixing forward and reverse-keyed items:
  Access                   35R 36R 9 8 7
  Understanding the modes  22 3 15 31 37R
  Valuing and savouring    12 18 11 27 44R
  Letting be               40R 46R 43R 47R 21
Wording and ids are pool 6's exactly (sf6_*), so scores line up with Study 1. One
fixed order for everyone, at every timepoint (a pre/post outcome should not change
order between administrations), drawn once by the platform's constrained shuffle:
factors spread, reverse-keyed items never adjacent and 2-3 per page, each reversal
off its partner's page.

Writes study1/sf-short-20.json, study1/psy240-sf-short-20.json and the migration
supabase/migrations/20261011_sf_short_form.sql (both questionnaires; the PSY240
class trial's baseline and final-survey steps move from psy240-sf-pool-5).

Usage:  python scripts/sense_foraging/build_short_form.py
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
from build_draft import SFS_POINTS, fallback_pages, likert, lit, questionnaire  # noqa: E402

POOL6 = json.loads((HERE / 'study1' / 'sf-pool6.json').read_text(encoding='utf-8'))
ROOT = HERE.parents[1]

FACTORS = {
    'Access': [35, 36, 9, 8, 7],
    'Understanding the modes': [22, 3, 15, 31, 37],
    'Valuing and savouring': [12, 18, 11, 27, 44],
    'Letting be': [40, 46, 43, 47, 21],
}
TRIAL_NODES = ['c93a06cf-c161-4e77-8e26-24158009c6e6',   # Class trial · baseline
               'd0fc050c-a6ba-4ddd-82e2-ef45da45ca4e']   # Class trial · final survey


def main():
    comps = {c['id']: c for p in POOL6['pages'] for c in p['components']}
    rev = set(POOL6['reverse_keyed'])
    sid = lambda n: f'sf6_{n}'
    items = [sid(n) for ids in FACTORS.values() for n in ids]
    assert len(items) == 20 == len(set(items))
    reversed_in = [i for i in items if i in rev]
    partners = [[a, b] for a, b in POOL6['interleave']['apart_pages'] if a in items and b in items]
    spec = {
        'items': items, 'page_sizes': [7, 7, 6],
        'clusters': {k.lower().replace(' ', '_'): [sid(n) for n in v] for k, v in FACTORS.items()},
        'cluster_min_gap': 3, 'cluster_max_per_page': 2,
        'groups': [{'items': reversed_in, 'min_gap': 2, 'max_per_page': 3, 'min_per_page': 2,
                    'max_run_outside': 4, 'avoid_positions': [1]}],
        'apart_pages': partners,
    }
    layout = fallback_pages(spec)          # one valid order, fixed seed

    def build(slug, name):
        pages = [{'id': f'sfs20_p{p}', 'components': [likert(i, comps[i]['question'], SFS_POINTS) for i in ids]}
                 for p, ids in enumerate(layout, 1)]
        d = questionnaire(slug, name, POOL6['instructions'], pages)
        d['factors'] = {k: [sid(n) for n in v] for k, v in FACTORS.items()}
        d['reverse_keyed'] = reversed_in
        d['scoring'] = {'method': 'mean', 'note': 'Reverse-keyed items are recoded 7 - x before averaging; "pna" is missing.',
                        'subscales': [{'name': k, 'method': 'mean', 'item_ids': [sid(n) for n in v],
                                       'reverse_items': [sid(n) for n in v if sid(n) in rev]} for k, v in FACTORS.items()]}
        d['source'] = 'Study 1 (osf.io/48r2y), short form chosen 2026-10-11; wording and ids = sf-pool6.'
        return d

    master = build('sf-short-20', 'Sense Foraging Scale, short form (20 items)')
    trial = build('psy240-sf-short-20', 'Paying attention')
    out = HERE / 'study1'
    for d in (master, trial):
        (out / f"{d['slug']}.json").write_text(json.dumps(d, ensure_ascii=False, indent=2), encoding='utf-8')

    sql = ['-- Sense Foraging Scale short form (20 items), from Study 1 (osf.io/48r2y; Norm, 2026-10-11).',
           '-- Generated by scripts/sense_foraging/build_short_form.py. Two questionnaires: the library master',
           '-- sf-short-20 and the PSY240 class trial copy psy240-sf-short-20 (neutral title "Paying attention").',
           '-- The trial\'s baseline and final-survey steps move off psy240-sf-pool-5 (34 items), which keeps',
           '-- its rows; the trial is inactive with no enrollments, and pool 5 has no responses.', '']
    for d in (master, trial):
        sql.append(f"INSERT INTO public.questionnaires (slug, name, definition) VALUES ({lit(d['slug'])}, {lit(d['name'])}, "
                   f"{lit(json.dumps(d, ensure_ascii=False))}::jsonb)\n  ON CONFLICT (slug) DO UPDATE SET definition = EXCLUDED.definition, "
                   "name = EXCLUDED.name, updated_at = now();")
    sql.append("UPDATE public.session_template_nodes\n   SET questionnaire_id = (SELECT id FROM public.questionnaires WHERE slug = 'psy240-sf-short-20'),\n"
               "       label = 'Paying attention (Sense Foraging short form)'\n"
               f" WHERE id IN ({', '.join(lit(n) for n in TRIAL_NODES)});")
    (ROOT / 'supabase' / 'migrations' / '20261011_sf_short_form.sql').write_text('\n'.join(sql) + '\n', encoding='utf-8')
    print('order:', ' | '.join(' '.join(i[4:] + ('R' if i in rev else '') for i in p) for p in layout))


if __name__ == '__main__':
    main()
